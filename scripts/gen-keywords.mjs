// Regenerate playground/keywords.js — the playground editor's two keyword
// lists — from the installed compiler's own table: `vilan --print-keywords`,
// which prints `lexing::KEYWORDS` and `lexing::CONTEXTUAL_KEYWORDS` (the one
// keyword table the TextMate grammar and the book's highlighter are generated
// from inside the toolchain repo). Until K27 the editor kept its own list by
// hand, and it drifted: no `css`, no `then`, `with`/`own`/`jump`/`borrows`
// painted everywhere though the lexer had demoted them to contextual words,
// and `resource` still listed after it became the `[resource]` attribute.
//
//   node scripts/gen-keywords.mjs        write playground/keywords.js
//
// then rebuild the editor bundle (cd playground/editor-src && npm run build),
// which inlines the file. tests/keywords.test.mjs regenerates in memory from
// whatever `vilan` the harness runs (CI installs the latest release) and
// fails when the committed file differs, so a toolchain that moves a keyword
// turns the site red until this is rerun.
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));

/// The compiler's table: `{ keywords: [...], contextual: [...] }`, where
/// `keywords` is every keyword and `contextual` the subset that is a keyword
/// only by position.
export function compilerTable() {
	const run = spawnSync("vilan", ["--print-keywords"], { encoding: "utf8" });
	if (run.error) throw run.error;
	if (run.status !== 0) throw new Error(`vilan --print-keywords exited ${run.status}: ${run.stderr}`);
	return JSON.parse(run.stdout);
}

const list = (words) => words.map((word) => JSON.stringify(word)).join(", ");

export function generate(table) {
	const contextual = [...table.contextual].sort();
	const reserved = table.keywords.filter((word) => !table.contextual.includes(word)).sort();
	return [
		"// GENERATED by scripts/gen-keywords.mjs from `vilan --print-keywords` — do not edit.",
		"// The compiler's keyword table (lexing::KEYWORDS + CONTEXTUAL_KEYWORDS), split",
		"// into the words that are ALWAYS keywords and the ones that are keywords only by",
		"// position; tests/keywords.test.mjs holds this file to the installed compiler.",
		"",
		`export const RESERVED = [${list(reserved)}];`,
		"",
		`export const CONTEXTUAL = [${list(contextual)}];`,
		"",
	].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	writeFileSync(`${root}playground/keywords.js`, generate(compilerTable()));
	console.log("wrote playground/keywords.js — now rebuild the editor bundle (playground/editor-src: npm run build)");
}
