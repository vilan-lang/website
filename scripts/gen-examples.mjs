// Regenerate playground/examples.js from playground/examples/*.vl.
//
// The output is deterministic (sorted names, JSON-escaped bodies), so the
// smoke gate can regenerate it in memory and byte-compare: an edited example
// with a stale examples.js fails the deploy instead of shipping quietly.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const dir = `${root}playground/examples`;

export function generate() {
	const names = readdirSync(dir).filter((name) => name.endsWith(".vl")).sort();
	const entries = names.map((name) => {
		const source = readFileSync(`${dir}/${name}`, "utf8");
		return `\t${JSON.stringify(name.slice(0, -3))}: ${JSON.stringify(source)},`;
	});
	return [
		"// GENERATED by scripts/gen-examples.mjs from playground/examples/*.vl — do not edit.",
		"window.VILAN_EXAMPLES = {",
		...entries,
		"};",
		"",
	].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	writeFileSync(`${root}playground/examples.js`, generate());
	console.log("wrote playground/examples.js");
}
