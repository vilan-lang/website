// Regenerate src/playground/examples.js from playground/examples/*.vl.
//
// The output lives under src/ because the playground leg BUNDLES it —
// `const asset::bundle` resolves against the package root, which is src/, and
// carrying it into `dist/` is what stopped the deploy hand-copying it.
//
// The output is deterministic (sorted names, JSON-escaped bodies), so the
// smoke gate can regenerate it in memory and byte-compare: an edited example
// with a stale examples.js fails the deploy instead of shipping quietly.
//
// It also carries the RETIRED examples' fingerprints (K25). The editor keeps
// a visitor's buffer in localStorage, so every visitor who once opened the
// counter kept the counter AS IT WAS — and after a language change that text
// is a broken program restored on every return visit, with nothing to say it
// was ours rather than theirs. playground/retired-examples.json records the
// fingerprint (playground/fingerprint.js) of every example text this
// playground has shipped and replaced; the editor swaps a restored buffer
// that matches one for the current example. Running this script maintains
// the record by itself: it reads the examples.js committed at HEAD, and every
// example whose text differs from it (or has disappeared) is retired. So the
// rule for editing an example stays what it was — edit the .vl, run this
// script, commit what it wrote (examples.js, and the record when it moved).
import { spawnSync } from "node:child_process";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { fingerprint } from "../playground/fingerprint.js";

const root = fileURLToPath(new URL("..", import.meta.url));
const dir = `${root}playground/examples`;
const retiredFile = `${root}playground/retired-examples.json`;

/// The current examples, name → source, in sorted order.
export function examples() {
	const names = readdirSync(dir).filter((name) => name.endsWith(".vl")).sort();
	return Object.fromEntries(names.map((name) => [name.slice(0, -3), readFileSync(`${dir}/${name}`, "utf8")]));
}

/// The retired record, fingerprint → example name.
export function retired() {
	return JSON.parse(readFileSync(retiredFile, "utf8"));
}

export function generate() {
	const current = examples();
	const gone = retired();
	return [
		"// GENERATED by scripts/gen-examples.mjs from playground/examples/*.vl — do not edit.",
		"window.VILAN_EXAMPLES = {",
		...Object.entries(current).map(([name, source]) => `\t${JSON.stringify(name)}: ${JSON.stringify(source)},`),
		"};",
		"// Fingerprints (playground/fingerprint.js) of every example text the playground",
		"// shipped and has since replaced: a restored buffer matching one is swapped for",
		"// the current example (scripts/gen-examples.mjs says why).",
		"window.VILAN_RETIRED_EXAMPLES = {",
		...Object.keys(gone)
			.sort()
			.map((key) => `\t${JSON.stringify(key)}: ${JSON.stringify(gone[key])},`),
		"};",
		"",
	].join("\n");
}

/// The examples the COMMITTED examples.js ships — HEAD's copy, not the
/// working tree's, so regenerating twice while an edit is in progress retires
/// only what was actually committed (and so shipped), never a draft. Evaluated,
/// not parsed, so whatever shape an older generator wrote still reads.
function shipped() {
	const head = spawnSync("git", ["show", "HEAD:src/playground/examples.js"], { cwd: root, encoding: "utf8" });
	if (head.status !== 0) return {};
	const host = {};
	new Function("window", head.stdout)(host);
	return host.VILAN_EXAMPLES ?? {};
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const current = examples();
	const gone = retired();
	let moved = false;
	for (const [name, source] of Object.entries(shipped())) {
		if (current[name] === source) continue;
		const key = fingerprint(source);
		if (!(key in gone)) {
			gone[key] = name;
			moved = true;
			console.log(`retired the shipped ${name} (${key})`);
		}
	}
	// A text that is current again (an edit reverted, an old version
	// restored) is not retired: the editor would swap a pristine copy of it.
	for (const [name, source] of Object.entries(current)) {
		const key = fingerprint(source);
		if (key in gone) {
			delete gone[key];
			moved = true;
			console.log(`un-retired ${name} (${key}): it is current again`);
		}
	}
	if (moved) {
		const sorted = Object.fromEntries(Object.keys(gone).sort().map((key) => [key, gone[key]]));
		writeFileSync(retiredFile, `${JSON.stringify(sorted, null, "\t")}\n`);
	}
	writeFileSync(`${root}src/playground/examples.js`, generate());
	console.log("wrote src/playground/examples.js");
}
